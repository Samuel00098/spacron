export const currentPresetTheme = writable<string | null>(null);

export function createPresetTheme(
  id: string,
  name: string,
  type: 'dark' | 'light',
  colors: Record<string, string>,
  syntax: Record<string, string>,
  backgroundImage?: string,
  backgroundOpacity?: number,
  backgroundBlur?: number
): Theme {
  return { id, name, type, colors, syntax, backgroundImage, backgroundOpacity, backgroundBlur };
}

/* ── The accent ───────────────────────────────────────────────────────
   Two accents, one per appearance mode — every preset below shares them,
   so the accent is a property of light-vs-dark, not of the wallpaper.
   Change these values and the whole app's accent moves with them.

   Both are the same indigo, pitched for the background they sit on. The
   light accent is deep enough to read as text and hold white button
   labels (6.0:1 on the page, 6.3:1 for the label). The dark accent is
   lifted to stay legible on near-black (6.2–6.5:1 across the three dark
   presets) — but that lifted tone is too pale to carry white text, so
   dark-mode buttons keep the deeper fill and only the hover lightens.
   Anything below 4.5:1 for button text fails AA at our label size. */

